// npm run build:skill: the skill's command-line tool as one file with no
// dependencies (Node 18 or later), skills/system-design-diagram/scripts/archslate.mjs,
// bundled from tools/archslate-cli with Archslate's own parser and file format.
//
// --check (part of npm run check) builds in memory and fails when the
// committed file is not what the sources build to.
import { build } from 'esbuild';
import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const outfile = join(root, 'skills', 'system-design-diagram', 'scripts', 'archslate.mjs');
const check = process.argv.includes('--check');

const result = await build({
  entryPoints: [join(root, 'tools', 'archslate-cli', 'cli.mjs')],
  outfile,
  write: !check,
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node18',
  minify: false,
  legalComments: 'inline',
  banner: { js: '#!/usr/bin/env node\n// Archslate command-line tool for the system-design-diagram skill. Generated by npm run build:skill from tools/archslate-cli; do not edit.' },
  logLevel: 'warning',
});

if (check) {
  const built = result.outputFiles[0].text;
  if (!existsSync(outfile) || readFileSync(outfile, 'utf8') !== built) {
    console.error('build:skill: skills/system-design-diagram/scripts/archslate.mjs is out of date: run npm run build:skill');
    process.exit(1);
  }
  console.log('build:skill: the skill\'s archslate.mjs matches its sources');
} else {
  console.log('built skills/system-design-diagram/scripts/archslate.mjs');
}
